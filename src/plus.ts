/**
 * «Плюс» — платные функции (план: docs/MONETIZATION.md):
 * - цвета уроков: цвета предметов и классов, свои цветовые метки, полоска в виджетах;
 * - акцентный цвет интерфейса, кроме основного зелёного;
 * - уведомления на телефоне: перед уроком, перед концом урока, сводка на завтра,
 *   выбор звука и «Не звенеть на уроке».
 *
 * Здесь — единственное место, где приложение спрашивает, есть ли «Плюс».
 * Пока «Плюс» нельзя купить (PLUS_ON_SALE = false), платные функции скрыты целиком:
 * их нет ни в настройках, ни в работе. Сохранённые настройки (метки, акцент, уведомления)
 * не стираются — включатся вместе с «Плюсом».
 */
export const PLUS_ON_SALE = false;

/** `VITE_PLUS=1 npm run dev` — посмотреть платные функции при разработке. */
const devPlus = import.meta.env?.VITE_PLUS === '1';

export function hasPlus(): boolean {
  return devPlus;
}

/** Показывать ли платную функцию: она куплена или её можно купить (тогда — со значком «Плюс»). */
export function showsPlus(): boolean {
  return hasPlus() || PLUS_ON_SALE;
}
